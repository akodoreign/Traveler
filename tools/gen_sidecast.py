def config(c):
    top, lower, accent, armor, lace = CLAN[c["clan"]]
    T = dict(top=top, lower=lower, accent=accent, armor=armor, lace=lace, eye=(96, 62, 44), build="normal",
             female=False, bangs="normal")
    T.update(c)
    if c["key"] in KITS and "kit" not in c:
        T["kit"] = KITS[c["key"]]
    return T


def main():
    preview_only = "--preview-only" in sys.argv
    only = set(sys.argv[sys.argv.index("--only") + 1].split(",")) if "--only" in sys.argv else None   # e.g. gonta
    cols, cell_w, cell_h = 9, g.FW * 2, g.FH + 10
    rows = (len(CAST) + cols - 1) // cols
    sheet = Image.new("RGBA", (cols * cell_w, rows * cell_h), (70, 98, 62, 255))
    d = ImageDraw.Draw(sheet)
    jpath = os.path.join(g.RES, "enemy_pic.json")
    j = json.load(open(jpath, encoding="utf-8"))
    tmpl = j["EP000"]
    for n, c in enumerate(CAST):
        if only and c["key"] not in only:
            continue
        T = config(c)
        r, cc = n // cols, n % cols
        for k, (kind, i) in enumerate((("idle", 0), ("attack", 1))):
            f = Image.fromarray(g.frame(T, kind, i), "RGBA")
            sheet.paste(f, (cc * cell_w + k * g.FW, r * cell_h), f)
        d.text((cc * cell_w + 3, r * cell_h + g.FH), c["name"], fill=(255, 255, 255, 255))
        if not preview_only:
            fname = "side_%s" % c["key"]
            sh = g.sheet(T)
            sh.save(os.path.join(g.PIC, fname + ".png"), optimize=True)
            e = json.loads(json.dumps(tmpl))
            e.update({"name": {"en": c["name"], "ja": c["name"]}, "pic3d": "/resource/enemy_pic/%s.png" % fname,
                      "aniuv": [g.COLS, g.ROWS], "memo": "side-cast sprite (tools/gen_sidecast.py)",
                      "gndpos": [0.5, (g.FH - g.GROUND - 1) / g.FH], "atkpos": [0.25, 0.55],
                      "cntpos": [0.5, 0.6], "scale": 1.45 * g.CAST_SCALE * g.HUMAN_SCALE * c.get("scale", 1.0), "flipx": True})
            e["animap"] = [{"id": k, "st": v[0], "en": v[1], "spd": v[2], "loop": v[3], "replay": not v[3]}
                           for k, v in g.animap_for(T).items()]          # v4 layout: per-weapon main attack
            j[epid(n)] = e
            foe = json.loads(json.dumps(e))
            foe.update({"flipx": False, "memo": "side-cast sprite as an enemy: faces the party (tools/gen_sidecast.py)"})
            j[foe_epid(n)] = foe
            if c["key"] in SS_ICON:
                badge(sh.copy()).save(os.path.join(g.PIC, fname + "_ss.png"), optimize=True)
                e2 = json.loads(json.dumps(e))
                e2["pic3d"] = "/resource/enemy_pic/%s_ss.png" % fname
                e2["memo"] = "side-cast sprite + side-story icon (tools/gen_sidecast.py)"
                j[ss_epid(c["key"])] = e2
        print("drew", c["name"])
    if not preview_only:
        json.dump(j, open(jpath, "w", encoding="utf-8"), ensure_ascii=False, indent="\t")
    if only:                                               # a partial run keeps the full preview sheet
        return
    big = sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST)
    out = os.path.join(g.PREVIEW, "sidecast.png")
    big.save(out)
    print(out)


if __name__ == "__main__":
    main()
