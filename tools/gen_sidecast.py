def badge(img):
    """Stamp the "?" tablet above the head in every frame cell of a sprite sheet."""
    px = img.load()
    for cy in range(0, img.height, g.FH):
        for cx in range(0, img.width, g.FW):
            box = img.crop((cx, cy, cx + g.FW, cy + g.FH)).split()[3].getbbox()
            if not box:
                continue
            top = box[1]
            xs = [x for x in range(box[0], box[2]) for y in range(top, min(top + 5, box[3]))
                  if px[cx + x, cy + y][3] > 0]
            mx = (min(xs) + max(xs)) // 2 if xs else (box[0] + box[2]) // 2
            ox, oy = cx + mx - 3, cy + max(0, top - len(BADGE) - 2)
            for r, row in enumerate(BADGE):
                for c, ch in enumerate(row):
                    if ch in BADGE_COL:
                        px[ox + c, oy + r] = BADGE_COL[ch]
    return img


def epid(n):
    """EP300+ for the first 50 side-cast entries, EP370-399 for the next 30 (EP350-369 are props / nezumi / map),
    then EP460-499 (EP400-436 are human enemies and monsters, EP437-449 beasts, EP450-459 boss banners), then EP540+
    (EP500-519 are more human enemies, EP520-539 more banners), up to EP699; then EP1100+ (EP700-1099 are foe_epid)."""
    if n < 50:
        return "EP%03d" % (300 + n)
    if n < 80:
        return "EP%03d" % (370 + n - 50)
    if n < 120:
        return "EP%03d" % (460 + n - 80)
    if n < 280:
        return "EP%03d" % (540 + n - 120)
    return "EP%d" % (1100 + n - 280)                 # (EP700+ are the party-facing foe copies: past them)


def foe_epid(n):
    """EP700+: the same sprite facing the party, for side-cast characters fought as enemies (a duel with Gusai,
    Shogen's test). The side-cast entries face the enemies (flipx, like the travelers); enemies stand on the left facing
    right with no flipx; same scale, so a duel reads eye to eye (user: "Gusai is backwards ... not facing the
    character")."""
    return "EP%03d" % (700 + n)


