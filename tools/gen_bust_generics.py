"""Stand-in dialog busts for speakers who don't have their own yet (user, 2026-11-08). Writes plugin/rokugan/RokuganBustGeneric.sk.
A real bust always wins (RokuganBust bustKey looks in bustnames first), so a finished one replaces its stand-in with no change here.
Men: the plain servant. Women: the village herbalist. Soldiers: the gate guard. Monsters, spirits and objects get none.
Rerun after new speakers are added: python -E tools/gen_bust_generics.py"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.normpath(os.path.join(HERE, "..", "_tools", "rpgcobo-tool", "project"))
MAN, WOMAN, SOLDIER = "npc_servant", "npc_village_herbalist", "npc_gate_guard"
NOT_PEOPLE = ("orochi", "oni no", "hioninmaru", "crow-tengu", "voice", "demon", "iron box", "giseiki", "ancestor", "kami", "goblin", "naga champion", "snake",
              "spirit", "ghost", "kansen", "lantern twins", "guardian", "note", "reader", "???", "ashimoshi")
ALIAS = {"mieko": "npc_isawa_mieko", "child-": "npc_child", "twin boys": "npc_child", "nezumi warrior": "npc_nezumi_warrior",
         "nezumi shaman": "npc_nezumi_shaman"}
WOMEN = ("priestess", "nun", "grandmother", "maid", "hostess", "attendant", "o-tamai", "nashiko", "fishwife", "actress", "widow", "dying healer")
SOLDIERS = ("guard", "sentry", "soldier", "ashigaru", "bushi", "spearman", "marine", "sergeant", "veteran", "commander", "general", "yojimbo",
            "captain", "deserter", "thug", "bandit", "berserker", "duelist", "duellist", "scout", "bodyguard")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    have = set()
    for line in open(os.path.join(PROJ, "plugin", "rokugan", "RokuganBustData.sk"), encoding="utf-8"):
        line = line.strip().replace(chr(92), "")
        if line.startswith('["') and '"] = "' in line:
            have.add(line[2:line.index('"] = "')])
    speakers = {}

    def walk(o):
        if isinstance(o, dict):
            if o.get("key") == "message_talk" and isinstance(o.get("name"), str) and o["name"].strip():
                speakers[o["name"].strip()] = 1
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    for f in ("map", "macro"):
        walk(json.load(open(os.path.join(PROJ, "data", f + ".json"), encoding="utf-8")))
    sex = {}
    for f in glob.glob(os.path.join(HERE, "pixelai_specs", "*.json")):
        s = json.load(open(f, encoding="utf-8"))
        p = s.get("prompt", "").lstrip()
        sex[s.get("name")] = "F" if p.startswith("1girl") else "M" if p.startswith("1boy") else None
    out, skipped = {}, []
    for name in sorted(speakers):
        base = name.split(" (")[0]
        if name.startswith("$") or name in have or base in have:
            continue
        low = name.lower()
        alias = next((k for a, k in ALIAS.items() if a in low), None)
        if alias:
            out[name] = alias
        elif any(w in low for w in NOT_PEOPLE):
            skipped.append(name)
        elif sex.get(base) == "F" or any(w in low for w in WOMEN):
            out[name] = WOMAN
        elif any(w in low for w in SOLDIERS):
            out[name] = SOLDIER
        else:
            out[name] = MAN
    q = chr(34)
    esc = lambda s: s.replace(chr(92), chr(92) * 2).replace(q, chr(92) + q)
    lines = ["//\tGenerated by tools/gen_bust_generics.py (do not edit): stand-in busts for speakers without their own.", "::Rokugan.bustgeneric <- {"]
    lines += ['\t["%s"] = "%s",' % (esc(k), v) for k, v in sorted(out.items())]
    lines.append("};")
    open(os.path.join(PROJ, "plugin", "rokugan", "RokuganBustGeneric.sk"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(len(out), "stand-ins;", len(skipped), "without a bust:", ", ".join(skipped))


if __name__ == "__main__":
    main()
